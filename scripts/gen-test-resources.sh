#!/usr/bin/env bash
# Generates the unit tests' resources from contract/: one JSON resource per golden fixture
# (Rez.JsonData.fixture_<name>, dashes as underscores) and the bolus calculator fixtures as integer rows
# (Rez.JsonData.oracle_<n>: [carbs or null, glucose or null, carb ratio mg/U, ISF, target, IOB mU,
# oracle total mU]), in chunks so no one resource is large. Written to tests/generated/ (git-ignored);
# scripts/build-and-test.sh runs it before compiling the tests.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import json, os
out = "tests/generated"
os.makedirs(out, exist_ok=True)
lines = ['<jsonDataResources>']
for name in sorted(os.listdir("contract/fixtures")):
    if name.endswith(".json"):
        rid = "fixture_" + name[:-5].replace("-", "_")
        lines.append(f'    <jsonData id="{rid}" filename="../../contract/fixtures/{name}" />')
lines.append('    <jsonData id="shared_constants" filename="../../contract/shared_constants.json" />')
rows = []
for line in open("contract/bolus_oracle_fixtures.jsonl"):
    r = json.loads(line)
    def milli(v):
        m = round(v * 1000)
        assert abs(m - v * 1000) < 1e-6, v
        return int(m)
    carbs = r["carbs"]
    assert carbs is None or float(carbs).is_integer(), r
    rows.append([None if carbs is None else int(carbs), r["bg"], milli(r["cr"]), r["isf"], r["tgt"],
                 milli(r["iob"]), milli(r["u"])])
chunk = 100
count = 0
for i in range(0, len(rows), chunk):
    path = f"oracle_{count}.json"
    json.dump(rows[i:i + chunk], open(os.path.join(out, path), "w"))
    lines.append(f'    <jsonData id="oracle_{count}" filename="{path}" />')
    count += 1
lines.append('</jsonDataResources>')
open(os.path.join(out, "contract.xml"), "w").write("\n".join(lines) + "\n")
open(os.path.join(out, "OracleCount.mc"), "w").write(
    "// Generated by scripts/gen-test-resources.sh from contract/bolus_oracle_fixtures.jsonl.\n"
    f"module OracleCount {{\n    const CHUNKS = {count};\n    const ROWS = {len(rows)};\n}}\n")
print(f"tests/generated: {len(os.listdir('contract/fixtures'))} fixtures, {len(rows)} calculator rows in {count} chunks")
PY
